-- Create icon component for a specific set
function M.createIconComponent(iconSetName)
    local icons = ICON_SETS[iconSetName]
    if not icons then
        error("Unknown icon set: " .. tostring(iconSetName))
    end

    return function(props)
        local React = require("react")
        local name = props.name
        local size = props.size or 24
        local color = props.color or "#000000"
        local style = props.style or {}

        local char = icons[name]
        if not char then
            char = "?"
        end

        return React.createElement("Text", {
            style = {
                fontSize = size,
                color = color,
                fontFamily = iconSetName,
                textAlign = "center",
                textAlignVertical = "center",
                width = size,
                height = size,
                lineHeight = size,
            },
        }, char)
    end
end

-- Pre-built icon components
M.MaterialIcons = M.createIconComponent("MaterialIcons")
M.FontAwesome = M.createIconComponent("FontAwesome")
M.Ionicons = M.createIconComponent("Ionicons")

-- Generic Icon component that accepts family prop
function M.Icon(props)
    local family = props.family or "MaterialIcons"
    local Component = M.createIconComponent(family)
    return Component(props)
end

-- Get icon char code for custom rendering
function M.getIconChar(iconSet, name)
    local set = ICON_SETS[iconSet]
    if set then
        return set[name]
    end
    return nil
end

return M
